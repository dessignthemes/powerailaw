def esc(c): return re.sub(r'([\[\]#:/.!%,()])',r'\\\1',c)
STATES={'':'','hover:':':hover','focus:':':focus','focus-within:':':focus-within','group-hover:':''}
rules=[]
seen=set()
pat=re.compile(r'(?<![\w-])((?:hover:|focus:|focus-within:)?)(bg|text|border|border-t|border-b|border-l|border-r|divide)-\[#([0-9A-Fa-f]{3,8})\](/\d+)?')
for m in pat.finditer(txt):
    pre,kind,hexv,alpha=m.group(1),m.group(2),m.group(3),m.group(4) or ''
    cls=m.group(0)
    if cls in seen: continue
    seen.add(cls)
    H=hexv.upper()
    if kind=='bg': d=BG.get(H)
    elif kind=='text': d=TEXT.get(hexv) or TEXT.get(H)
    else: d=BORDER.get(H) or BG.get(H)
    if not d: continue
    sel='html[data-theme="dark"] .'+esc(cls)+STATES[pre]
    if kind=='bg': prop='background-color'
    elif kind=='text': prop='color'
    elif kind=='divide': rules.append(sel+' > :not(:last-child){border-color:'+d+'}'); continue
    elif kind=='border': prop='border-color'
    else: prop={'border-t':'border-top-color','border-b':'border-bottom-color','border-l':'border-left-color','border-r':'border-right-color'}[kind]+''
    rules.append(f'{sel}{{{prop}:{d}}}')
# bg-white variants
for m in set(re.findall(r'(?<![\w-])((?:hover:|focus:|focus-within:)?bg-white(?:/\d+)?)(?![\w-])',txt)):
    pre='hover:' if m.startswith('hover:') else 'focus:' if m.startswith('focus:') else 'focus-within:' if m.startswith('focus-within:') else ''
    alpha=re.search(r'/(\d+)$',m)
    col='#1a1d23' if not alpha else 'rgba(26,29,35,%.2f)'%(int(alpha.group(1))/100)
    rules.append('html[data-theme="dark"] .'+esc(m)+STATES[pre]+'{background-color:'+col+'}')
out='/* Dark mode (generated by Claude from the colours used in src/; regenerate when new colours are added).\n   Light colours written as Tailwind classes are swapped for dark ones when <html data-theme="dark">. */\n'+'\n'.join(sorted(rules))+'\n'
open('src/app/dark.css','w').write(out)
print(len(rules))
