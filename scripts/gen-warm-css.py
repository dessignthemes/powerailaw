# The warm colour scheme LawPower uses. The code itself is written with light
# blue-greys; this file swaps them for soft warm greys (<html data-palette="warm">,
# always set in src/app/layout.tsx; dark mode has its own colours in dark.css).
# Regenerate after adding new light colours:  python3 scripts/gen-warm-css.py
import re, glob, colorsys

txt = '\n'.join(open(p).read() for p in glob.glob('src/**/*.tsx', recursive=True) + glob.glob('src/**/*.ts', recursive=True))

WARM_HUE = 40 / 360  # a very light, warm stone (soft beige-grey), not a strong beige

# Colours with a fixed warm partner (the left menu is lighter than the page, like the reference).
FIXED = {
    'EEF0F7': '#FAFAF9',  # left menu
    'CED0DB': '#EFEEEB',  # left menu: current page / hover
}

def warm(hexv):
    """A light blue-grey -> a soft warm stone of about the same lightness. None = leave as it is."""
    h = hexv.lstrip('#').upper()
    if len(h) == 3: h = ''.join(c * 2 for c in h)
    if len(h) != 6: return None
    if h in FIXED: return FIXED[h]
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    hue, light, sat = colorsys.rgb_to_hls(r, g, b)
    deg = hue * 360
    # Only the cool neutrals: light, blue-ish (or grey), not a real colour (info blue, tags).
    if light < 0.66 or sat > 0.45: return None
    if not (185 <= deg <= 265) and sat > 0.06: return None
    if r == g == b and light > 0.985: return None  # white stays white
    s2 = min(0.13, sat * 0.25 + 0.05)  # just a hint of warmth
    l2 = min(0.985, light + 0.006)
    r2, g2, b2 = colorsys.hls_to_rgb(WARM_HUE, l2, s2)
    return '#%02X%02X%02X' % (round(r2 * 255), round(g2 * 255), round(b2 * 255))

def esc(c): return re.sub(r'([\[\]#:/.!%,()])', r'\\\1', c)

SEL = 'html[data-palette="warm"]:not([data-theme="dark"])'
STATES = {'': '', 'hover:': ':hover', 'focus:': ':focus', 'focus-within:': ':focus-within'}
pat = re.compile(r'(?<![\w-])((?:hover:|focus:|focus-within:)?)(bg|border|border-t|border-b|border-l|border-r|divide|ring)-\[#([0-9A-Fa-f]{3,8})\](/\d+)?')
rules, seen = [], set()
for m in pat.finditer(txt):
    pre, kind, hexv, alpha = m.group(1), m.group(2), m.group(3), m.group(4) or ''
    cls = m.group(0)
    if cls in seen: continue
    seen.add(cls)
    w = warm(hexv)
    if not w: continue
    if alpha:
        a = int(alpha[1:]) / 100
        w = 'rgba(%d,%d,%d,%.2f)' % (int(w[1:3], 16), int(w[3:5], 16), int(w[5:7], 16), a)
    sel = SEL + ' .' + esc(cls) + STATES[pre]
    if kind == 'bg': rules.append(f'{sel}{{background-color:{w}}}')
    elif kind == 'divide': rules.append(f'{sel} > :not(:last-child){{border-color:{w}}}')
    elif kind == 'ring': rules.append(f'{sel}{{--tw-ring-color:{w}}}')
    elif kind == 'border': rules.append(f'{sel}{{border-color:{w}}}')
    else: rules.append(f'{sel}{{{ {"border-t": "border-top-color", "border-b": "border-bottom-color", "border-l": "border-left-color", "border-r": "border-right-color"}[kind] }:{w}}}')

O, B = warm('#ECEFF6'), warm('#E1E5EE')
head = f'''/* ── Warm beige colour scheme (generated by scripts/gen-warm-css.py) ──────────
   Always on (<html data-palette="warm">, set in src/app/layout.tsx); dark mode
   uses dark.css instead. */
{SEL} {{
  --sidebar: #fafaf9;
  --cream: #fbfaf8;
  --page: #f6f5f3;
  --beige: #ebe8e2;
  --card-alt: #f5f4f1;
  --nav: #efeeeb;
  --chip: #f1f0ed;
  --line: #e7e5e0;
  --btn: #e8e5df;
  --btn-hover: #dfdbd3;
  --btn-ring: #cdc8be;
  --muted: #74706a;
  --muted-light: #a8a29e;
}}
/* Widget frames, dropdown menus and pop-ups: the soft frame around them. */
{SEL} [class*="0_0_0_6px_#ECEFF6"] {{ box-shadow: 0 0 0 6px {O}, 0 0 0 7px {B}, 0 3px 8px -1px rgba(40, 36, 30, 0.06) !important; }}
{SEL} [class*="0_0_0_6px_#ECEFF6"][class*="0_24px_50px"] {{ box-shadow: 0 0 0 6px {O}, 0 0 0 7px {B}, 0 24px 50px -18px rgba(40, 30, 15, 0.28) !important; }}
{SEL} [class*="0_0_0_7px_#ECEFF6"] {{ box-shadow: 0 0 0 7px {O}, 0 0 0 8px {B}, 0 14px 40px -20px rgba(40, 30, 15, 0.25) !important; }}
{SEL} .fixed.inset-0[class*="bg-black/"][class*="justify-center"]:not([class*="bg-black/80"]) > *:not(.fixed):not(script) {{
  box-shadow: 0 0 0 7px {O}, 0 0 0 8px {B}, 0 30px 80px -24px rgba(40, 30, 15, 0.32) !important;
}}
{SEL} .lp-theme-btn {{ background-color: #e8e5df; }}
{SEL} .lp-theme-btn:hover {{ background-color: #dfdbd3; }}
/* Light blue-grey Tailwind colours → beige. */
'''
open('src/app/warm.css', 'w').write(head + '\n'.join(sorted(rules)) + '\n')
print(len(rules), 'rules')
